    @classmethod
    def _load_knowledge_base(cls) -> Dict[str, Any]:
        """Load knowledge base from JSON file with caching"""
        if cls._knowledge_base_cache is not None:
            return cls._knowledge_base_cache
        
        try:
            # Get the path to the JSON file
            base_dir = Path(__file__).parent.parent
            json_path = base_dir / "data" / "remediation_knowledge_base.json"
            
            logger.info(f"Loading knowledge base from: {json_path}")
            
            with open(json_path, 'r', encoding='utf-8') as f:
                json_data = json.load(f)
            
            # Convert JSON disease IDs to Python-friendly format
            converted_data = {}
            for json_id, disease_data in json_data.items():
                python_id = cls._disease_id_map.get(json_id, json_id.lower())
                # Update the disease_id in the data to match Python format
                disease_data['disease_id'] = python_id
                converted_data[python_id] = disease_data
            
            cls._knowledge_base_cache = converted_data
            logger.info(f"✓ Loaded {len(converted_data)} diseases from JSON")
            
            return converted_data
            
        except FileNotFoundError:
            logger.error(f"Knowledge base JSON file not found at {json_path}")
            return {}
        except json.JSONDecodeError as e:
            logger.error(f"Invalid JSON in knowledge base file: {e}")
            return {}
        except Exception as e:
            logger.error(f"Error loading knowledge base: {e}")
            return {}
    
    @classmethod
    @property
    def KNOWLEDGE_BASE(cls) -> Dict[str, Any]:
        """Property to access knowledge base (loads from JSON on first access)"""
        return cls._load_knowledge_base()
    
